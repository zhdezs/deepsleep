SHARP_STRATEGY_ORDER = ["zen", "logic", "question", "praise", "echo", "care"]


def sharp_lines_for(strategy):
    """返回某策略的尖锐语料（不存在时回退为全量补刀）。"""
    data = SHARP_LINES.get(strategy)
    if not data:
        return {
            "first_lines": SHARP_BLOW,
            "follow_ups": SHARP_BLOW,
            "escalate_lines": SHARP_BLOW,
        }
    return data


def sharp_blow_for(strategy):
    """把通用补刀语料挂到某策略名下，用于追加输出。"""
    return SHARP_LINES[strategy]["name"], SHARP_BLOW
