# 实时组装入口
# ----------------------------------------------------------------------

def compose(troll_text, category, strategy, agg, turns, sid, rising=True, learned=None):
    """针对对方具体言论实时组装一条回怼。

    长度不设限，按攻击强度自适应：
    - 低强度：干净利落，引用头 + 一两个短打 + 收尾（三五行带走）；
    - 高强度/对方升级：多段展开，策略攻防 + 分类拆台 + 短打 + 收尾（长文破防）。

    参数：
        troll_text  对方原始言论（将被抽取引用片段）
        category    攻击类型
        strategy    主策略
        agg         攻击强度 0-10
        turns       当前轮次（从 0 开始）
        sid         会话标识（用于去重）
        rising      对方是否升级
        learned     话术记忆库召回的「实战验证过有效」的段落（默认 None）。
                    注入后混入组装池，且带会话级去重，让学过的招数有机会上场。
    返回：多行字符串（已脱敏，零脏话）
    """
    quotes = _extract_quotes(troll_text)
    quote = quotes[0] if quotes else None
    word = _attack_word(troll_text)

    # 段落规模：数量在小范围内浮动，避免每次观感固定
    if agg >= 7:
        n_skel = random.choice([3, 3, 4])
        n_cat = random.choice([2, 2, 3])
        n_quick = random.choice([2, 3])
        n_dissect = 2
    elif agg >= 4 or (rising and agg >= 5):
        n_skel = random.choice([2, 2, 3])
        n_cat = random.choice([1, 2])
        n_quick = random.choice([1, 2])
        n_dissect = 1 if len(quotes) >= 2 else 0
    else:
        n_skel = random.choice([1, 1, 2])
        n_cat = random.choice([0, 1])
        n_quick = 1
        n_dissect = 0

    skel_pool = list(_SKELETONS.get(strategy, _SKELETONS["question"]))
    cat_pool = list(_CATEGORY_LINES.get(category, _CATEGORY_LINES["general"]))

    skels = random.sample(skel_pool, min(n_skel, len(skel_pool)))
    cats = random.sample(cat_pool, min(n_cat, len(cat_pool)))
    mid = skels + cats
    random.shuffle(mid)

    # 实战话术注入：随机挑（不重复），直接进入组装，让学过的招数每次换着用
    extra = []
    if learned:
        extra = [mask_profanity(x) for x in learned
                 if x and MIN_LEARNED_LEN <= len(x.strip()) <= MAX_LEARNED_LEN]
        extra = random.sample(extra, min(2, len(extra)))

    # 逐条拆解段：把对方多个原话片段并列拆台（观感最「针对」）
    dissects = []
    if n_dissect and len(quotes) >= 2:
        qseq = "…".join("「%s」" % q for q in quotes[:3])
        for _ in range(n_dissect):
            dissects.append(random.choice(_DISSECT_TEMPLATES).replace("{q}", qseq))

    quick_pool = list(_QUICK_CUTS)
    quicks = [_fill(_pick_unique(quick_pool, sid), quote=quote, word=word, turn=turns)
              for _ in range(min(n_quick, len(quick_pool)))]

    seq = mid + extra + dissects + quicks
    random.shuffle(seq)

    parts = [_fill(_pick_unique(_QUOTE_OPENS, sid), quote=quote, word=word, turn=turns)]
    parts.extend(_fill(x, quote=quote, word=word, turn=turns) for x in seq)
    parts.append(_fill(_pick_unique(_FINISHERS, sid), quote=quote, word=word, turn=turns))

    return mask_profanity("\n".join(parts))


def live_alternatives(troll_text, category, strategy, n=3):
    """生成 n 条不同组合的实时回复（不推进会话状态，供手动挑选）。"""
    out = []
    for i in range(n):
        sid = "__alt_%d_%d__" % (id(out), i)
        quote = _extract_quote(troll_text)
        word = _attack_word(troll_text)
        skel_pool = list(_SKELETONS.get(strategy, _SKELETONS["question"]))
        cat_pool = list(_CATEGORY_LINES.get(category, _CATEGORY_LINES["general"]))
        skels = random.sample(skel_pool, min(2, len(skel_pool)))
        cats = random.sample(cat_pool, min(1, len(cat_pool)))
        mid = skels + cats
        random.shuffle(mid)
        parts = [_fill(random.choice(_QUOTE_OPENS), quote=quote, word=word, turn=1)]
        for skel in mid:
            parts.append(_fill(skel, quote=quote, word=word, turn=1))
        parts.append(_fill(random.choice(_FINISHERS), quote=quote, word=word, turn=1))
        out.append(mask_profanity("\n".join(parts)))
    return out
