# ----------------------------------------------------------------------
# 会话级去重历史
# ----------------------------------------------------------------------

_history = {}  # sid -> [已用句子...]


def _pick_unique(pool, sid, bucket=6, prefer_new=True):
    """从池中随机取一句，避免与同会话最近使用过的句子重复。"""
    used = _history.setdefault(sid, [])
    candidates = [s for s in pool if s not in used[-bucket:]] or pool
    line = random.choice(candidates)
    used.append(line)
    _history[sid] = used[-bucket * 2:]
    return line


def _fill(template, quote=None, word=None, turn=None):
    out = template
    if quote:
        out = out.replace("{q}", quote)
    else:
        out = out.replace("{q}", "你上面这段话")
    if word:
        out = out.replace("{w}", word)
    else:
        out = out.replace("{w}", "你用的那些词")
    if turn is not None:
        out = out.replace("{t}", str(turn))
    return out


